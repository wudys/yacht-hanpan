import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

import { ASSET_SOURCE_CATALOG } from '../src/source-catalog.ts';

export const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const MIME_BY_EXTENSION = Object.freeze({
  '.mp3': 'audio/mpeg',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
  '.wav': 'audio/wav',
});

function dimensions(extension, bytes) {
  if (extension === '.png' && bytes.length >= 24 && bytes.toString('ascii', 1, 4) === 'PNG') {
    return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
  }
  if (extension === '.svg') {
    const source = bytes.toString('utf8');
    const viewBox = source.match(/viewBox=["'](?:[-.\d]+\s+){2}([-.\d]+)\s+([-.\d]+)["']/u);
    if (viewBox) return { width: Number(viewBox[1]), height: Number(viewBox[2]) };
    const width = source.match(/\bwidth=["']([\d.]+)(?:px)?["']/u);
    const height = source.match(/\bheight=["']([\d.]+)(?:px)?["']/u);
    if (width && height) return { width: Number(width[1]), height: Number(height[1]) };
  }
  return {};
}

export async function buildManifest(root = PACKAGE_ROOT) {
  const entries = [];
  for (const source of [...ASSET_SOURCE_CATALOG].sort((left, right) =>
    left.id.localeCompare(right.id),
  )) {
    const absolutePath = path.join(root, source.sourcePath);
    const bytes = await readFile(absolutePath);
    const extension = path.extname(source.sourcePath).toLowerCase();
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const slug = source.id.replaceAll('.', '/');
    entries.push({
      id: source.id,
      kind: source.kind,
      url: `/assets/game/${slug}/${sha256}${extension}`,
      bytes: bytes.length,
      sha256,
      mime: MIME_BY_EXTENSION[extension],
      ...dimensions(extension, bytes),
    });
  }
  return entries;
}

async function listFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) => {
        const child = path.join(directory, entry.name);
        return entry.isDirectory() ? listFiles(child) : child;
      }),
    )
  ).flat();
}

export async function verifySourceAssets({ root = PACKAGE_ROOT } = {}) {
  const errors = [];
  const catalogIds = new Set();
  const sourcePaths = new Set();

  for (const source of ASSET_SOURCE_CATALOG) {
    if (catalogIds.has(source.id)) errors.push(`duplicate asset id: ${source.id}`);
    if (sourcePaths.has(source.sourcePath))
      errors.push(`duplicate source path: ${source.sourcePath}`);
    catalogIds.add(source.id);
    sourcePaths.add(source.sourcePath);
  }

  const filesRoot = path.join(root, 'files');
  for (const absolutePath of await listFiles(filesRoot)) {
    if (path.basename(absolutePath) === '.DS_Store') continue;
    const relativePath = path.relative(root, absolutePath).split(path.sep).join('/');
    if (!sourcePaths.has(relativePath)) errors.push(`orphaned asset file: ${relativePath}`);
  }

  const manifest = await buildManifest(root);
  const urls = new Set();
  for (const entry of manifest) {
    if (!entry.mime) errors.push(`unknown MIME type: ${entry.id}`);
    if (urls.has(entry.url)) errors.push(`duplicate asset URL: ${entry.url}`);
    urls.add(entry.url);
  }
  return { errors, manifest };
}

export async function writeGeneratedManifest(root = PACKAGE_ROOT) {
  const { errors, manifest } = await verifySourceAssets({ root });
  if (errors.length > 0) throw new Error(errors.join('\n'));
  const source = `import type { GameAssetManifestEntry } from './types';\n\n// Generated by scripts/generate-manifest.mjs. Do not edit manually.\nexport const GAME_ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies readonly GameAssetManifestEntry[];\n`;
  const outputPath = path.join(root, 'src/manifest.generated.ts');
  await writeFile(
    outputPath,
    await format(source, {
      ...(await resolveConfig(outputPath)),
      filepath: outputPath,
    }),
  );
  return manifest;
}

export async function syncPublic(targetRoot, root = PACKAGE_ROOT) {
  if (!targetRoot) throw new Error('sync target is required');
  const manifest = await buildManifest(root);
  const { GAME_ASSET_MANIFEST } = await import('../src/manifest.generated.ts');
  if (JSON.stringify(manifest) !== JSON.stringify(GAME_ASSET_MANIFEST)) {
    throw new Error('generated manifest is stale; run bun --filter @repo/game-assets generate');
  }
  const target = path.resolve(targetRoot, 'assets/game');
  await rm(target, { recursive: true, force: true });
  const sourceById = new Map(ASSET_SOURCE_CATALOG.map((entry) => [entry.id, entry]));
  for (const entry of manifest) {
    const source = sourceById.get(entry.id);
    if (!source) throw new Error(`missing source metadata: ${entry.id}`);
    const output = path.join(targetRoot, entry.url.replace(/^\//u, ''));
    await mkdir(path.dirname(output), { recursive: true });
    await cp(path.join(root, source.sourcePath), output);
    const outputStat = await stat(output);
    if (outputStat.size !== entry.bytes) throw new Error(`copied byte size mismatch: ${entry.id}`);
  }
  return manifest.length;
}
